#!/usr/bin/env bash
# ============================================================
#  Atour DataAgent 服务管理（Linux / macOS，源码优先模式）
#
#  与 service.sh 的区别：
#    service.sh        走 `octop service`，加载 site-packages 里的 octop
#    service-local.sh  额外注入 PYTHONPATH=<仓库>/src，
#                      让「本地改的源码」盖过 site-packages
#                      —— 对应 Windows 的 run-atour.bat / service.bat
#
#  用法:
#    ./service-local.sh run       前台运行（调试用，Ctrl+C 退出）
#    ./service-local.sh start     安装(如需要)并后台启动服务
#    ./service-local.sh stop      停止服务
#    ./service-local.sh restart   重启服务
#    ./service-local.sh status    查看状态 + HTTP 健康检查
#    ./service-local.sh logs      跟踪日志
#    ./service-local.sh dropin    仅写入 systemd drop-in（不改主 unit）
#    ./service-local.sh uninstall 移除 drop-in 并重启（回到 site-packages）
#    ./service-local.sh help      显示帮助
#
#  原理（关键）:
#    PYTHONPATH 在 sys.path 中排在 site-packages 之前，
#    所以 `import octop` 会解析到 <仓库>/src/octop，而不是 venv 里的拷贝。
#    前端产物同理：后端读 <octop.__file__>/../dashboard，
#    设了 PYTHONPATH 后即读 <仓库>/src/octop/dashboard（含品牌）。
#    → 改源码后只需重启服务，无需重新 pip install。
#
#  systemd 注入方式:
#    不改主 unit（`octop service` 会管理它），而是写 drop-in:
#      user   scope -> ~/.config/systemd/user/octop.service.d/20-local-source.conf
#      system scope -> /etc/systemd/system/octop.service.d/20-local-source.conf
#    drop-in 会被 systemd 叠加到主 unit 上，且 `octop service` 不会覆盖它。
#
#  环境变量(可选):
#    OCTOP_SRC_ROOT  源码仓库根（默认 = 本脚本所在目录）
#    OCTOP_HOME      数据目录（默认 $HOME/.octop）
#    OCTOP_BIN       octop 可执行文件（默认自动探测）
#    SERVICE_SCOPE   user | system | auto(默认)
#    BIND_HOST       监听地址（默认沿用 config.json）
#    BIND_PORT       监听端口（默认沿用 config.json）
#    DROPIN_NAME     drop-in 文件名（默认 20-local-source.conf）
# ============================================================
set -euo pipefail

# ── 定位源码根（与 Windows 脚本的 ROOT 等价，但自动推导，不硬编码）─────
_SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${OCTOP_SRC_ROOT:-$_SCRIPT_DIR}"
SRC_DIR="$ROOT/src"

OCTOP_HOME="${OCTOP_HOME:-$HOME/.octop}"
VENV="$OCTOP_HOME/venv"
SERVICE_SCOPE="${SERVICE_SCOPE:-auto}"
BIND_HOST="${BIND_HOST:-}"
BIND_PORT="${BIND_PORT:-}"
DROPIN_NAME="${DROPIN_NAME:-20-local-source.conf}"
LOG_FILE="$OCTOP_HOME/logs/octop.log"

C_BOLD=$'\033[1m'; C_DIM=$'\033[2m'; C_GREEN=$'\033[32m'
C_YELLOW=$'\033[33m'; C_RED=$'\033[31m'; C_RESET=$'\033[0m'

info()  { printf "%s\n" "  $*"; }
ok()    { printf "  ${C_GREEN}%s${C_RESET}\n" "$*"; }
warn()  { printf "  ${C_YELLOW}%s${C_RESET}\n" "$*"; }
err()   { printf "  ${C_RED}%s${C_RESET}\n" "$*" >&2; }

# ── 前置校验（对应 bat 里的 if not exist 检查）─────────────────
require_source() {
  if [[ ! -f "$SRC_DIR/octop/__init__.py" ]]; then
    err "未找到源码目录: $SRC_DIR/octop"
    info "请确认 OCTOP_SRC_ROOT 指向正确的仓库路径，或把本脚本放在仓库根目录"
    exit 1
  fi
}

resolve_octop() {
  if [[ -n "${OCTOP_BIN:-}" && -x "$OCTOP_BIN" ]]; then
    printf "%s" "$OCTOP_BIN"; return 0
  fi
  local c
  for c in "$VENV/bin/octop" "$OCTOP_HOME/bin/octop" \
           "$OCTOP_HOME/venv/bin/octop"; do
    [[ -x "$c" ]] && { printf "%s" "$c"; return 0; }
  done
  if command -v octop >/dev/null 2>&1; then
    command -v octop; return 0
  fi
  return 1
}

OCTOP=""
need_octop() {
  if ! OCTOP="$(resolve_octop)"; then
    err "未找到 octop 可执行文件"
    info "请先安装:  bash scripts/install.sh"
    info "或手动指定:  export OCTOP_BIN=/path/to/octop"
    exit 1
  fi
}

# ── systemd drop-in（核心：注入 PYTHONPATH）────────────────────
resolve_scope() {
  case "$SERVICE_SCOPE" in
    user|system) printf "%s" "$SERVICE_SCOPE"; return ;;
  esac
  if [[ "$(id -u)" == "0" ]]; then printf "system"; else printf "user"; fi
}

dropin_dir() {
  local scope; scope="$(resolve_scope)"
  if [[ "$scope" == "user" ]]; then
    printf "%s" "$HOME/.config/systemd/user/octop.service.d"
  else
    printf "%s" "/etc/systemd/system/octop.service.d"
  fi
}

dropin_path() { printf "%s/%s" "$(dropin_dir)" "$DROPIN_NAME"; }

write_dropin() {
  require_source
  local scope dir path content
  scope="$(resolve_scope)"
  dir="$(dropin_dir)"
  path="$(dropin_path)"

  content="$(cat <<EOF
# Generated by service-local.sh — 让 octop 从本地源码加载（源码优先）。
# 删除本文件即可回到 site-packages 版本；不要手改，重跑 start/dropin 会覆盖。
[Service]
Environment="PYTHONPATH=$SRC_DIR"
EOF
)"

  if [[ "$scope" == "system" && "$(id -u)" != "0" ]]; then
    info "写入系统级 drop-in（需要 sudo）: $path"
    printf "%s\n" "$content" | sudo tee "$path" >/dev/null
  else
    mkdir -p "$dir"
    printf "%s\n" "$content" > "$path"
  fi
  ok "drop-in 已写入: $path"
  info "  Environment=PYTHONPATH=$SRC_DIR"
}

reload_and_restart() {
  local scope; scope="$(resolve_scope)"
  local sudo_prefix=()
  if [[ "$scope" == "system" && "$(id -u)" != "0" ]]; then
    sudo_prefix=(sudo)
  fi
  local sysctl_args=()
  [[ "$scope" == "user" ]] && sysctl_args=(--user)

  "${sudo_prefix[@]}" systemctl "${sysctl_args[@]}" daemon-reload
  ok "systemd 配置已重载"
}

# ── 健康检查 ──────────────────────────────────────────────────
read_bind_host() {
  [[ -n "$BIND_HOST" ]] && { printf "%s" "$BIND_HOST"; return; }
  local cfg="$OCTOP_HOME/config.json" v=""
  if [[ -f "$cfg" ]]; then
    v="$(sed -n 's/.*"bind_host"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$cfg" | head -n1)"
  fi
  [[ -z "$v" || "$v" == "0.0.0.0" ]] && v="127.0.0.1"
  printf "%s" "$v"
}
read_bind_port() {
  [[ -n "$BIND_PORT" ]] && { printf "%s" "$BIND_PORT"; return; }
  local cfg="$OCTOP_HOME/config.json" v=""
  if [[ -f "$cfg" ]]; then
    v="$(sed -n 's/.*"port"[[:space:]]*:[[:space:]]*\([0-9]\{1,5\}\).*/\1/p' "$cfg" | head -n1)"
  fi
  [[ -z "$v" ]] && v="8088"
  printf "%s" "$v"
}
probe_http() {
  local url code
  url="http://$(read_bind_host):$(read_bind_port)/api/health"
  if command -v curl >/dev/null 2>&1; then
    code="$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 "$url" 2>/dev/null || true)"
  else
    code=""
  fi
  if [[ -n "$code" && "$code" != "000" ]]; then
    ok "health: HTTP $code   $url"
  else
    warn "health: 未能探测到 HTTP 响应 ($url)"
  fi
}

scope_args() { printf -- "--scope %s" "$(resolve_scope)"; }

# 打印当前生效的 octop 加载路径（源码 vs site-packages）
show_source_status() {
  local py=""
  for c in "$VENV/bin/python" "$(command -v python3 2>/dev/null || true)"; do
    [[ -n "$c" && -x "$c" ]] && { py="$c"; break; }
  done
  if [[ -z "$py" ]]; then
    warn "未找到 python，跳过源码路径检查"
    return
  fi
  local loaded
  loaded="$(PYTHONPATH="$SRC_DIR" "$py" -c 'import octop,inspect;print(inspect.getfile(octop))' 2>/dev/null || true)"
  if [[ "$loaded" == "$SRC_DIR/octop/__init__.py" ]]; then
    ok "octop 加载自源码: $loaded"
  elif [[ -n "$loaded" ]]; then
    warn "octop 加载自其他位置: $loaded"
  else
    warn "无法探测 octop 加载路径"
  fi
}

# ── 命令实现 ──────────────────────────────────────────────────
cmd_run() {
  require_source
  local py="$VENV/bin/python"
  if [[ ! -x "$py" ]]; then
    py="$(command -v python3 || true)"
  fi
  [[ -x "$py" ]] || { err "未找到 python（期望 $VENV/bin/python）"; exit 1; }

  local port host
  port="$(read_bind_port)"; host="$(read_bind_host)"
  [[ -n "$BIND_HOST" ]] && host="$BIND_HOST"

  printf "%s\n" "============================================================"
  printf "%s\n" "  Atour DataAgent - run from source (前台)"
  printf "%s\n" "============================================================"
  info "源码根   : $ROOT"
  info "PYTHONPATH: $SRC_DIR"
  info "Python   : $py"
  info "数据目录 : $OCTOP_HOME"
  info "监听     : $host:$port"
  printf "%s\n" "------------------------------------------------------------"
  show_source_status
  printf "%s\n" "------------------------------------------------------------"

  # 与 run-atour.bat 等价：设 PYTHONPATH + 在仓库根运行
  cd "$ROOT"
  PYTHONPATH="$SRC_DIR" OCTOP_HOME="$OCTOP_HOME" \
    "$py" -m octop run --host "$host" --port "$port"
}

cmd_start() {
  need_octop
  printf "%s\n" "============================================================"
  printf "%s\n" "  Atour DataAgent - start (源码优先)"
  printf "%s\n" "============================================================"
  info "源码根   : $ROOT"
  info "octop    : $OCTOP"
  info "数据目录 : $OCTOP_HOME"
  info "安装范围 : $(resolve_scope)"
  info "日志文件 : $LOG_FILE"
  printf "%s\n" "------------------------------------------------------------"

  # 先确保服务已安装（octop service start 会按需安装主 unit）
  local args=()
  [[ -n "$BIND_HOST" ]] && args+=(--host "$BIND_HOST")
  [[ -n "$BIND_PORT" ]] && args+=(--port "$BIND_PORT")
  # shellcheck disable=SC2086
  "$OCTOP" service start ${args[@]+"${args[@]}"} $(scope_args)

  # 再注入源码 drop-in 并重载，使 PYTHONPATH 生效
  printf "%s\n" "------------------------------------------------------------"
  write_dropin
  reload_and_restart

  # shellcheck disable=SC2086
  "$OCTOP" service restart $(scope_args) || true
  printf "%s\n" "------------------------------------------------------------"
  probe_http
  show_source_status
}

cmd_stop() {
  need_octop
  # shellcheck disable=SC2086
  "$OCTOP" service stop $(scope_args)
}

cmd_restart() {
  need_octop
  printf "%s\n" "============================================================"
  printf "%s\n" "  Atour DataAgent - restart (源码优先)"
  printf "%s\n" "============================================================"
  [[ -f "$(dropin_path)" ]] || warn "drop-in 不存在，先写入以启用源码加载"
  write_dropin
  reload_and_restart
  # shellcheck disable=SC2086
  "$OCTOP" service restart $(scope_args) || true
  printf "%s\n" "------------------------------------------------------------"
  probe_http
  show_source_status
}

cmd_status() {
  need_octop
  printf "%s\n" "============================================================"
  printf "%s\n" "  Atour DataAgent - status"
  printf "%s\n" "============================================================"
  info "源码根   : $ROOT"
  info "octop    : $OCTOP"
  info "数据目录 : $OCTOP_HOME"
  info "安装范围 : $(resolve_scope)"
  local dp; dp="$(dropin_path)"
  if [[ -f "$dp" ]]; then
    ok "源码 drop-in: $dp"
    sed -n 's/^/    /p' "$dp"
  else
    warn "源码 drop-in 不存在（当前加载 site-packages 版本）: $dp"
  fi
  printf "%s\n" "------------------------------------------------------------"
  # shellcheck disable=SC2086
  "$OCTOP" service status $(scope_args) || true
  printf "%s\n" "------------------------------------------------------------"
  probe_http
  show_source_status
}

cmd_logs() {
  local scope; scope="$(resolve_scope)"
  if command -v journalctl >/dev/null 2>&1; then
    local journal
    if [[ "$scope" == "user" ]]; then
      journal="journalctl --user -u octop -f -n 60"
    else
      journal="journalctl -u octop -f -n 60"
    fi
    [[ -f "$LOG_FILE" ]] && info "同时可直接查看: tail -f $LOG_FILE"
    info "执行: $journal"
    printf "%s\n" "------------------------------------------------------------"
    eval "$journal"
  elif [[ -f "$LOG_FILE" ]]; then
    info "跟踪日志: $LOG_FILE   (Ctrl+C 退出)"
    printf "%s\n" "------------------------------------------------------------"
    tail -n 60 -f "$LOG_FILE"
  else
    warn "日志文件尚未生成: $LOG_FILE"
  fi
}

cmd_uninstall() {
  local dp; dp="$(dropin_path)"
  if [[ ! -f "$dp" ]]; then
    warn "drop-in 不存在，无需清理: $dp"
    return 0
  fi
  local scope; scope="$(resolve_scope)"
  if [[ "$scope" == "system" && "$(id -u)" != "0" ]]; then
    sudo rm -f "$dp"
  else
    rm -f "$dp"
  fi
  ok "已移除 drop-in: $dp"
  reload_and_restart
  need_octop
  # shellcheck disable=SC2086
  "$OCTOP" service restart $(scope_args) || true
  ok "服务已重启，恢复为 site-packages 版本"
}

cmd_help() {
  cat <<EOF
============================================================
  Atour DataAgent 服务管理  Linux / macOS（源码优先）
============================================================
  用法:
    ./service-local.sh run        前台运行（调试，Ctrl+C 退出）
    ./service-local.sh start      安装(如需要)并后台启动（注入源码 drop-in）
    ./service-local.sh stop       停止服务
    ./service-local.sh restart    重启服务
    ./service-local.sh status     查看状态 + 健康检查 + 源码加载路径
    ./service-local.sh logs       跟踪日志
    ./service-local.sh dropin     仅写入 systemd drop-in
    ./service-local.sh uninstall  移除 drop-in 并重启（回到 site-packages）
    ./service-local.sh help       显示本帮助

  与 service.sh 的区别:
    service.sh        加载 venv 里 site-packages 的 octop
    service-local.sh  注入 PYTHONPATH=<源码根>/src，加载本地改的源码
                      → 改源码后只需 restart，无需重新 pip install

  源码根（当前推导值）:
    ROOT       = $ROOT
    PYTHONPATH = $SRC_DIR
    （可用 OCTOP_SRC_ROOT 覆盖）

  环境变量:
    OCTOP_SRC_ROOT=${OCTOP_SRC_ROOT:-<脚本所在目录>}
    OCTOP_HOME=$OCTOP_HOME
    OCTOP_BIN=${OCTOP_BIN:-<自动探测>}
    SERVICE_SCOPE=$SERVICE_SCOPE   (user | system | auto)
    BIND_HOST=${BIND_HOST:-<沿用 config.json>}
    BIND_PORT=${BIND_PORT:-<沿用 config.json>}
    DROPIN_NAME=$DROPIN_NAME
============================================================
EOF
}

# ── 分发 ──────────────────────────────────────────────────────
CMD="${1:-help}"
case "$CMD" in
  run)            shift; cmd_run "$@" ;;
  start)          shift; cmd_start "$@" ;;
  stop)           shift; cmd_stop "$@" ;;
  restart)        shift; cmd_restart "$@" ;;
  status)         shift; cmd_status "$@" ;;
  logs|log)       shift; cmd_logs "$@" ;;
  dropin)         shift; write_dropin ;;
  uninstall|revert) shift; cmd_uninstall "$@" ;;
  help|-h|--help) cmd_help ;;
  *)              err "未知命令: $CMD"; echo; cmd_help; exit 1 ;;
esac
